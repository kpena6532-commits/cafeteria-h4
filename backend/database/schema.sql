CREATE DATABASE IF NOT EXISTS cafeteria_h4 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cafeteria_h4;

CREATE TABLE IF NOT EXISTS configuracion (
  clave VARCHAR(80) PRIMARY KEY, valor TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS categorias (
  id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL, orden INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS productos (
  id INT AUTO_INCREMENT PRIMARY KEY, categoria_id INT NULL, nombre VARCHAR(120) NOT NULL,
  descripcion TEXT NOT NULL, precio DECIMAL(10,2) NOT NULL, imagen TEXT NOT NULL,
  disponible BOOLEAN NOT NULL DEFAULT TRUE, orden INT NOT NULL DEFAULT 0,
  FOREIGN KEY (categoria_id) REFERENCES categorias(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS servicios (
  id INT AUTO_INCREMENT PRIMARY KEY, titulo VARCHAR(120) NOT NULL, descripcion TEXT NOT NULL,
  icono VARCHAR(30) NOT NULL DEFAULT '☕', activo BOOLEAN NOT NULL DEFAULT TRUE, orden INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS especialidades (
  id INT AUTO_INCREMENT PRIMARY KEY, producto_id INT NOT NULL, etiqueta VARCHAR(100) NOT NULL,
  orden INT NOT NULL DEFAULT 0, FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS galeria (
  id INT AUTO_INCREMENT PRIMARY KEY, titulo VARCHAR(120) NOT NULL, imagen TEXT NOT NULL,
  orden INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS horarios (
  id INT AUTO_INCREMENT PRIMARY KEY, dias VARCHAR(90) NOT NULL, horas VARCHAR(90) NOT NULL,
  orden INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS preguntas_frecuentes (
  id INT AUTO_INCREMENT PRIMARY KEY, pregunta VARCHAR(255) NOT NULL, respuesta TEXT NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS contactos (
  id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL,
  asunto VARCHAR(150) NOT NULL, mensaje TEXT NOT NULL, fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
