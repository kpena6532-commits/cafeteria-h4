const express = require('express');
const cors = require('cors');
const rateLimit = require('express-rate-limit');
const api = require('./controllers/public');
const chatbot = require('./chatbot/ollama');
const errorHandler = require('./middleware/error');
const app = express();
app.disable('x-powered-by');
app.use(cors({ origin: (process.env.FRONTEND_URL || 'http://localhost:4200').split(',') }));
app.use(express.json({ limit: '30kb' }));
const wrap = fn => (req, res, next) => Promise.resolve(fn(req, res)).catch(next);
app.get('/api/health', (req, res) => res.json({ status: 'ok' }));
app.get('/api/tienda', wrap(api.storefront));
app.get('/api/contenido/:section', wrap(api.section));
app.post('/api/contactos', rateLimit({ windowMs: 60000, limit: 6 }), wrap(api.contact));
app.post('/api/chatbot', rateLimit({ windowMs: 60000, limit: 12 }), wrap(chatbot.ask));
app.use((req, res) => res.status(404).json({ error: 'Ruta no encontrada' }));
app.use(errorHandler);
module.exports = app;
